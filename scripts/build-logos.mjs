// Generates src/data/logos.js from simple-icons (mono, brand colour) with iconify "logos" (full colour) as fallback.
// Run: node scripts/build-logos.mjs
import * as si from 'simple-icons';
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';

const logosSet = JSON.parse(readFileSync('node_modules/@iconify-json/logos/icons.json', 'utf8'));

const MONO = {
  python: 'siPython', javascript: 'siJavascript', typescript: 'siTypescript', c: 'siC', mysql: 'siMysql', html: 'siHtml5', css: 'siCss',
  tailwind: 'siTailwindcss', react: 'siReact', nextjs: 'siNextdotjs', framer: 'siFramer', gsap: 'siGreensock', threejs: 'siThreedotjs',
  node: 'siNodedotjs', express: 'siExpress', mongodb: 'siMongodb', axios: 'siAxios', jwt: 'siJsonwebtokens', docker: 'siDocker',
  firebase: 'siFirebase', git: 'siGit', github: 'siGithub', linux: 'siLinux', postman: 'siPostman', figma: 'siFigma', gemini: 'siGooglegemini',
  kaggle: 'siKaggle', google: 'siGoogle', geeksforgeeks: 'siGeeksforgeeks', tata: 'siTata', unstop: 'siUnstop',
  redis: 'siRedis', fastapi: 'siFastapi', celery: 'siCelery', trivy: 'siTrivy',
};
// full-colour fallbacks where simple-icons has no entry
const COLOR = { microsoft: 'microsoft-icon', azure: 'azure-icon', aws: 'aws', vscode: 'visual-studio-code', linkedin: 'linkedin-icon' };

const lum = (hex) => {
  const [r, g, b] = [0, 2, 4].map((i) => parseInt(hex.slice(i, i + 2), 16) / 255);
  return 0.2126 * r + 0.7152 * g + 0.0722 * b;
};

const out = {};
for (const [key, exp] of Object.entries(MONO)) {
  const icon = si[exp];
  if (!icon) { console.warn('missing simple-icon', key); continue; }
  // very dark brand colours would vanish on a dark page, so use white on hover instead
  const hex = lum(icon.hex) < 0.12 ? 'ffffff' : icon.hex;
  out[key] = { t: 'm', d: icon.path, c: `#${hex}` };
}
for (const [key, name] of Object.entries(COLOR)) {
  const icon = logosSet.icons[name];
  if (!icon) { console.warn('missing logo', key); continue; }
  let body = icon.body.replaceAll('#252f3e', 'currentColor').replaceAll('#000', 'currentColor');
  out[key] = { t: 'c', b: body, w: icon.width ?? logosSet.width ?? 256, h: icon.height ?? logosSet.height ?? 256 };
}

mkdirSync('src/data', { recursive: true });
writeFileSync('src/data/logos.js', `// Generated by scripts/build-logos.mjs. Do not edit by hand.\nexport const LOGOS = ${JSON.stringify(out)};\n`);
console.log('logos written:', Object.keys(out).length);
